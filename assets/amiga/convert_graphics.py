BLOCK_DISPLAY_MASK = 1<<14
DO_DISPLAY_MASK = 1

def gen_codes(i):
    im = (i<<1)
    return im | DO_DISPLAY_MASK,((0x10000 - im) %0x10000) | DO_DISPLAY_MASK

